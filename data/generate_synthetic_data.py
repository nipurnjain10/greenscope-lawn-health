"""Write the primary and robustness CSV files, metadata, and the data dictionary."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.config import (  # noqa: E402
    DATA_DIR,
    GENERATOR_VERSION,
    LABEL_NOISE_SD,
    N_MAIN,
    N_ROBUSTNESS,
    SEED_MAIN,
    SEED_ROBUSTNESS,
)
from src.data_validation import validate_saved_datasets  # noqa: E402
from src.synthetic_data import generate_inspections, write_data_dictionary  # noqa: E402
from src.utilities import package_versions, sha256_file, utc_now_iso, write_json  # noqa: E402


def main() -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    primary, primary_summary = generate_inspections(N_MAIN, SEED_MAIN, scenario="main")
    thresholds = (
        primary_summary["thresholds"]["low_lt"],
        primary_summary["thresholds"]["high_ge"],
    )
    robust, robust_summary = generate_inspections(
        N_ROBUSTNESS,
        SEED_ROBUSTNESS,
        scenario="robustness",
        thresholds=thresholds,
    )
    primary_path = DATA_DIR / "synthetic_lawn_inspections.csv"
    robust_path = DATA_DIR / "robustness_scenarios.csv"
    primary.to_csv(primary_path, index=False)
    robust.to_csv(robust_path, index=False)
    write_data_dictionary(DATA_DIR / "data_dictionary.md")

    metadata = {
        "generator_version": GENERATOR_VERSION,
        "label_noise_sd": LABEL_NOISE_SD,
        "seed_main": SEED_MAIN,
        "seed_robustness": SEED_ROBUSTNESS,
        "n_main": N_MAIN,
        "n_robustness": N_ROBUSTNESS,
        "class_rule": (
            "On the primary sample, Low is a noisy observed-feature score below the 33rd percentile and "
            "High is that score at or above the 67th percentile. Moderate is the interval "
            "between those frozen cutoffs. The robustness sample uses the same cutoffs. "
            "The score is computed from recorded measurements, not from the hidden latents used only to create feature dependence."
        ),
        "class_thresholds": primary_summary["thresholds"],
        "class_counts_main": primary_summary["class_counts"],
        "class_counts_robustness": robust_summary["class_counts"],
        "missingness_main": primary_summary["missingness_rate"],
        "missingness_robustness": robust_summary["missingness_rate"],
        "component_std_main": primary_summary["component_std"],
        "fingerprint_sha256_main": sha256_file(primary_path),
        "fingerprint_sha256_robustness": sha256_file(robust_path),
        "feature_columns": list(primary.columns),
        "python_version": sys.version.split()[0],
        "package_versions": package_versions(),
        "created_at_utc": utc_now_iso(),
        "provenance": (
            "All rows are synthetic observations generated by this project. "
            "No customer records and no external dataset rows were copied into the CSV files."
        ),
        "robustness_shifts": [
            "Heat latent mean 0.85 instead of 0, with standard deviation 1.05.",
            "Water-supply latent mean -0.55 instead of 0, with standard deviation 1.05.",
            "Rainfall scale multiplied by 0.62.",
            "Grass mix shifted toward bermudagrass and zoysiagrass.",
            "Foot-traffic score shifted upward by 0.35.",
            "Higher missingness on pH, nitrogen, phosphorus, and potassium.",
            "Same label formula and the primary sample's frozen score cutoffs.",
        ],
        "notes": [
            "Continuous draws are clipped to the documented simulation bounds inside the generator, before the CSV is written. Validation then checks those bounds; it does not clip rows to force a pass.",
            "Generator 1.0.0 put hidden latents directly into the risk score. A training-only pilot then gave about 0.64 validation accuracy for logistic regression, while a random forest memorised the training rows. Generator 1.1.0 scores interacting observed measurements and adds Gaussian noise with standard deviation 0.15. A further validation-only check of gradient-boosting capacity selected 300 trees at learning rate 0.05. The held-out test partition was not used for these choices.",
            "If a later version changes LABEL_NOISE_SD or the score formula, bump GENERATOR_VERSION and regenerate every artifact.",
        ],
    }
    write_json(DATA_DIR / "metadata.json", metadata)
    print(json.dumps({
        "primary_classes": primary_summary["class_counts"],
        "robust_classes": robust_summary["class_counts"],
        "thresholds": primary_summary["thresholds"],
        "component_std": primary_summary["component_std"],
        "missingness_main": primary_summary["missingness_rate"],
    }, indent=2))
    results = validate_saved_datasets()
    if not all(item["passed"] for item in results):
        raise SystemExit("Validation failed. See reports/data_validation_report.md")
    print("Validation passed.")


if __name__ == "__main__":
    main()
